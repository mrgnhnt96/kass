//! The model calls a dictation session makes to the Python worker
//! (`backend/routes/stream_models.py`): Whisper for each phrase or the whole
//! recording, Qwen3 for cleanup and Command Mode, and the hints that keep
//! them warm and hold training off while the user dictates.
//!
//! The worker runs the models and nothing else: the session builds the
//! cleanup prompt and post-processes what comes back.

use std::time::Duration;

use axum::body::Body;
use axum::http::{header, Method, Request, StatusCode};
use http_body_util::BodyExt;
use hyper::body::Incoming;
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};

use crate::proxy::Proxy;

/// One phrase is seconds of audio at most, a minute once recognition fell
/// behind; the first call after launch also loads Whisper.
const RECOGNIZE_TIMEOUT: Duration = Duration::from_secs(120);
/// The whole-recording fallback can be an hour of audio.
const RECOGNIZE_FILE_TIMEOUT: Duration = Duration::from_secs(30 * 60);
/// A cleanup is one phrase, or the whole take; a model load may come first.
const CLEANUP_TIMEOUT: Duration = Duration::from_secs(120);
/// A rewrite may write up to 4096 tokens on the largest model.
const COMMAND_TIMEOUT: Duration = Duration::from_secs(300);
/// Paging a model back in reads gigabytes.
const RESIDENT_TIMEOUT: Duration = Duration::from_secs(60);
const QUICK_TIMEOUT: Duration = Duration::from_secs(5);

/// What the worker answered, or why there's no answer: the worker's own
/// `detail` when it gave one, which a session shows as its refinement error.
pub type Answer<T> = Result<T, String>;

/// A phrase for Whisper.
#[derive(Clone, Debug, Default, Serialize)]
pub struct Recognize {
    /// The sample rate of the PCM sent with it.
    pub rate: u32,
    pub language: Option<String>,
    pub stt_model: Option<String>,
    /// The sentence the phrase continues: earlier phrases, or the field's text.
    pub previous_text: Option<String>,
    /// Dictionary terms, most important first.
    pub vocabulary: Vec<String>,
    /// Keep the decode's word alignment, for how the phrase was said.
    pub alignment: bool,
}

/// The whole recording for Whisper, when the phrases couldn't be joined.
#[derive(Clone, Debug, Default, Serialize)]
pub struct RecognizeFile {
    pub path: String,
    pub language: Option<String>,
    pub stt_model: Option<String>,
    pub previous_text: Option<String>,
    pub vocabulary: Vec<String>,
    /// Skip Whisper when no voice is heard: for uploads, which no one
    /// checked yet. The session checked its own take.
    pub check_speech: bool,
}

#[derive(Clone, Debug, PartialEq, Deserialize)]
pub struct Recognized {
    pub text: String,
    /// The alignment kept in the worker, for [`alignment_words`].
    #[serde(default)]
    pub alignment: Option<String>,
    /// Time spent in the model, as the worker measured it.
    pub seconds: f64,
}

/// A word Whisper wrote, punctuation attached, and when it was said in
/// seconds from the phrase's start.
#[derive(Clone, Debug, PartialEq, Deserialize)]
pub struct Word {
    pub text: String,
    pub start: f64,
    pub end: f64,
}

/// A style's cleanup prompt, as the session built it.
#[derive(Clone, Debug, Default, Serialize)]
pub struct CleanupPrompt {
    pub model_size: String,
    /// The style's cleanup flags, which pick its personal or shared adapter;
    /// None runs the base model.
    pub flags: Option<Value>,
    pub system: String,
    /// Example turns: what was said, then what it should become.
    pub examples: Vec<(String, String)>,
    /// The prompt cache the call continues: one per writing style.
    pub cache_key: Option<String>,
}

/// One cleanup generation.
#[derive(Clone, Debug, Serialize)]
pub struct Generate {
    /// Names the generation for [`stop`]; unique among running ones.
    pub id: String,
    pub prompt: String,
    /// Text the output mostly copies, for lookup decoding: "" for the prompt
    /// alone, the previous cleanup of the same tail, or None for none.
    pub hint: Option<String>,
    pub max_tokens: u32,
    pub temperature: f32,
    #[serde(flatten)]
    pub cleanup: CleanupPrompt,
}

#[derive(Clone, Debug, PartialEq, Deserialize)]
pub struct Generated {
    /// The model's output as it came, before any of the session's rules.
    pub text: String,
    pub model: String,
    /// Ended early by [`stop`]: `text` is what was generated by then.
    pub stopped: bool,
    pub seconds: f64,
}

/// The JSON head of a recognize body, its length first (u32 LE), then the
/// PCM as s16le.
fn recognize_body(request: &Recognize, pcm: &[i16]) -> Vec<u8> {
    let head = serde_json::to_vec(request).expect("a phrase's head serializes");
    let mut body = Vec::with_capacity(4 + head.len() + pcm.len() * 2);
    body.extend_from_slice(&(head.len() as u32).to_le_bytes());
    body.extend_from_slice(&head);
    for sample in pcm {
        body.extend_from_slice(&sample.to_le_bytes());
    }
    body
}

/// Why a call has no answer: the worker's status when it gave one, and
/// its `detail` (or what went wrong on the way).
#[derive(Clone, Debug, PartialEq)]
pub struct Failure {
    pub status: Option<StatusCode>,
    pub detail: String,
}

impl Failure {
    fn other(detail: impl Into<String>) -> Self {
        Self {
            status: None,
            detail: detail.into(),
        }
    }

    /// The worker turned the request down (422): a model that isn't
    /// downloaded, a rewrite that came back empty.
    pub fn refused(&self) -> bool {
        self.status == Some(StatusCode::UNPROCESSABLE_ENTITY)
    }
}

impl From<Failure> for String {
    fn from(failure: Failure) -> Self {
        failure.detail
    }
}

async fn send(
    proxy: &Proxy,
    path: &str,
    content_type: &str,
    body: Vec<u8>,
) -> Result<hyper::Response<Incoming>, Failure> {
    let request = Request::builder()
        .method(Method::POST)
        .uri(format!("http://{}{path}", proxy.worker()))
        .header(header::CONTENT_TYPE, content_type)
        .body(Body::from(body))
        .map_err(|e| Failure::other(e.to_string()))?;
    let response = proxy
        .client()
        .request(request)
        .await
        .map_err(|e| Failure::other(format!("the model worker didn't answer: {e}")))?;
    if response.status().is_success() {
        return Ok(response);
    }
    let status = response.status();
    let bytes = response
        .into_body()
        .collect()
        .await
        .map_err(|e| Failure::other(e.to_string()))?
        .to_bytes();
    Err(Failure {
        status: Some(status),
        detail: failure(status, &bytes),
    })
}

fn failure(status: StatusCode, body: &[u8]) -> String {
    serde_json::from_slice::<Value>(body)
        .ok()
        .and_then(|value| value.get("detail")?.as_str().map(str::to_owned))
        .unwrap_or_else(|| format!("{status}: {}", String::from_utf8_lossy(body)))
}

async fn fetch<T: for<'de> Deserialize<'de>>(
    proxy: &Proxy,
    path: &str,
    content_type: &str,
    body: Vec<u8>,
    timeout: Duration,
) -> Result<T, Failure> {
    let answer = async {
        let response = send(proxy, path, content_type, body).await?;
        let bytes = response
            .into_body()
            .collect()
            .await
            .map_err(|e| Failure::other(e.to_string()))?
            .to_bytes();
        serde_json::from_slice(&bytes).map_err(|e| Failure::other(e.to_string()))
    };
    tokio::time::timeout(timeout, answer)
        .await
        .map_err(|_| Failure::other(format!("the model worker didn't answer in {timeout:?}")))?
}

async fn call<T: for<'de> Deserialize<'de>>(
    proxy: &Proxy,
    path: &str,
    content_type: &str,
    body: Vec<u8>,
    timeout: Duration,
) -> Answer<T> {
    Ok(fetch(proxy, path, content_type, body, timeout).await?)
}

async fn call_json<T: for<'de> Deserialize<'de>>(
    proxy: &Proxy,
    path: &str,
    body: &impl Serialize,
    timeout: Duration,
) -> Answer<T> {
    let body = serde_json::to_vec(body).map_err(|e| e.to_string())?;
    call(proxy, path, "application/json", body, timeout).await
}

/// Whisper's text for one phrase of `rate` Hz mono PCM. The session checks
/// for a voice first; the worker doesn't.
pub async fn recognize(proxy: &Proxy, request: &Recognize, pcm: &[i16]) -> Answer<Recognized> {
    let body = recognize_body(request, pcm);
    call(
        proxy,
        "/worker/recognize",
        "application/octet-stream",
        body,
        RECOGNIZE_TIMEOUT,
    )
    .await
}

/// Whisper's text for a whole recording the session wrote.
pub async fn recognize_file(proxy: &Proxy, request: &RecognizeFile) -> Answer<Recognized> {
    #[derive(Deserialize)]
    struct Text {
        text: String,
        seconds: f64,
    }
    let answer: Text = call_json(
        proxy,
        "/worker/recognize/file",
        request,
        RECOGNIZE_FILE_TIMEOUT,
    )
    .await?;
    Ok(Recognized {
        text: answer.text,
        alignment: None,
        seconds: answer.seconds,
    })
}

/// Whisper's text for an uploaded file in any format the worker decodes
/// (`POST /transcribe`), and the audio's length in seconds. Silence is "".
pub async fn transcribe_upload(
    proxy: &Proxy,
    path: &str,
    language: Option<&str>,
    stt_model: &str,
) -> Result<(String, f64), Failure> {
    #[derive(Deserialize)]
    struct Transcribed {
        text: String,
        duration: f64,
    }
    let body = json!({
        "path": path,
        "language": language,
        "stt_model": stt_model,
        "check_speech": true,
        "decode": true,
    });
    let body = serde_json::to_vec(&body).map_err(|e| Failure::other(e.to_string()))?;
    let answer: Transcribed = fetch(
        proxy,
        "/worker/recognize/file",
        "application/json",
        body,
        RECOGNIZE_FILE_TIMEOUT,
    )
    .await?;
    Ok((answer.text, answer.duration))
}

/// The words of a phrase recognized with `alignment`, worked out in the
/// worker off its model thread. Each alignment answers once.
pub async fn alignment_words(proxy: &Proxy, alignment: &str) -> Answer<Vec<Word>> {
    #[derive(Deserialize)]
    struct Words {
        words: Vec<Word>,
    }
    let path = format!("/worker/alignments/{alignment}/words");
    let answer: Words = call_json(proxy, &path, &json!({}), RECOGNIZE_TIMEOUT).await?;
    Ok(answer.words)
}

/// Run a cleanup, calling `partial` with the text generated so far as it
/// grows (the latest only, when several tokens came between reads).
pub async fn generate(
    proxy: &Proxy,
    request: &Generate,
    partial: impl FnMut(&str),
) -> Answer<Generated> {
    generate_within(proxy, request, CLEANUP_TIMEOUT, partial).await
}

/// [`generate`], given `timeout` to finish.
pub async fn generate_within(
    proxy: &Proxy,
    request: &Generate,
    timeout: Duration,
    partial: impl FnMut(&str),
) -> Answer<Generated> {
    tokio::time::timeout(timeout, read_generation(proxy, request, partial))
        .await
        .map_err(|_| format!("the cleanup didn't finish in {timeout:?}"))?
}

async fn read_generation(
    proxy: &Proxy,
    request: &Generate,
    mut partial: impl FnMut(&str),
) -> Answer<Generated> {
    #[derive(Deserialize)]
    struct Line {
        partial: Option<String>,
        error: Option<String>,
    }
    let body = serde_json::to_vec(request).map_err(|e| e.to_string())?;
    let mut body = send(proxy, "/worker/cleanup/generate", "application/json", body)
        .await?
        .into_body();
    let mut pending = Vec::new();
    while let Some(frame) = body.frame().await {
        let frame = frame.map_err(|e| e.to_string())?;
        let Some(data) = frame.data_ref() else {
            continue;
        };
        pending.extend_from_slice(data);
        while let Some(end) = pending.iter().position(|&byte| byte == b'\n') {
            let line: Vec<u8> = pending.drain(..=end).collect();
            let value: Value = serde_json::from_slice(&line).map_err(|e| e.to_string())?;
            let fields: Line = serde_json::from_value(value.clone()).map_err(|e| e.to_string())?;
            if let Some(error) = fields.error {
                return Err(error);
            }
            if let Some(text) = fields.partial {
                partial(&text);
                continue;
            }
            return serde_json::from_value(value).map_err(|e| e.to_string());
        }
    }
    Err("the cleanup ended without its text".into())
}

/// End the running generation `id` before its next token; its [`generate`]
/// returns the text so far, marked stopped. Whether it was still running.
pub async fn stop(proxy: &Proxy, id: &str) -> bool {
    #[derive(Deserialize)]
    struct Stopped {
        stopped: bool,
    }
    let path = format!("/worker/cleanup/{id}/stop");
    match call_json::<Stopped>(proxy, &path, &json!({}), QUICK_TIMEOUT).await {
        Ok(answer) => answer.stopped,
        Err(error) => {
            eprintln!("[server] couldn't stop a cleanup in the model worker: {error}");
            false
        }
    }
}

/// Put a style's prompt in the model's cache while the user speaks.
pub async fn prefill_cleanup(proxy: &Proxy, prompt: &CleanupPrompt) -> Answer<()> {
    call_json::<Value>(proxy, "/worker/cleanup/prefill", prompt, CLEANUP_TIMEOUT).await?;
    Ok(())
}

/// Load the cleanup model and the style's adapter before the first phrase.
pub async fn load_cleanup(proxy: &Proxy, model_size: &str, flags: Option<&Value>) -> Answer<()> {
    let body = json!({ "model_size": model_size, "flags": flags });
    call_json::<Value>(proxy, "/worker/cleanup/load", &body, CLEANUP_TIMEOUT).await?;
    Ok(())
}

/// Put Command Mode's prompt and the selection in the cache while the user
/// speaks the instruction.
pub async fn command_prefill(proxy: &Proxy, selection: &str, model_size: &str) -> Answer<()> {
    let body = json!({ "selection": selection, "model_size": model_size });
    call_json::<Value>(proxy, "/worker/command/prefill", &body, COMMAND_TIMEOUT).await?;
    Ok(())
}

/// The selection rewritten by `instruction`, and the model that wrote it.
pub async fn command_rewrite(
    proxy: &Proxy,
    selection: &str,
    instruction: &str,
    model_size: &str,
) -> Answer<(String, String)> {
    Ok(rewrite(proxy, selection, instruction, model_size).await?)
}

/// [`command_rewrite`], saying whether the worker refused the request or
/// failed running it.
pub async fn rewrite(
    proxy: &Proxy,
    selection: &str,
    instruction: &str,
    model_size: &str,
) -> Result<(String, String), Failure> {
    #[derive(Deserialize)]
    struct Rewritten {
        text: String,
        model: String,
    }
    let body =
        json!({ "selection": selection, "instruction": instruction, "model_size": model_size });
    let body = serde_json::to_vec(&body).map_err(|e| Failure::other(e.to_string()))?;
    let answer: Rewritten = fetch(
        proxy,
        "/worker/command/rewrite",
        "application/json",
        body,
        COMMAND_TIMEOUT,
    )
    .await?;
    Ok((answer.text, answer.model))
}

/// The Whisper model a dictation set to `configured` runs: a model trained
/// on the user's voice stands in for it while active.
pub async fn speech_model(proxy: &Proxy, configured: &str) -> Answer<String> {
    #[derive(Deserialize)]
    struct Model {
        model: String,
    }
    let body = json!({ "configured": configured });
    let answer: Model = call_json(proxy, "/worker/speech-model", &body, QUICK_TIMEOUT).await?;
    Ok(answer.model)
}

/// Read back whatever of the loaded models macOS paged out.
pub async fn keep_resident(proxy: &Proxy, reason: &str, llm: bool, stt: bool) -> Answer<()> {
    let body = json!({ "reason": reason, "llm": llm, "stt": stt });
    call_json::<Value>(proxy, "/worker/keep-resident", &body, RESIDENT_TIMEOUT).await?;
    Ok(())
}

/// A dictation in progress, which holds training off in the worker until
/// it's ended, or dropped.
pub struct Foreground {
    proxy: Option<Proxy>,
}

/// Hold training off while a dictation runs.
pub async fn begin_foreground(proxy: &Proxy) -> Answer<Foreground> {
    call_json::<Value>(proxy, "/worker/foreground/begin", &json!({}), QUICK_TIMEOUT).await?;
    Ok(Foreground {
        proxy: Some(proxy.clone()),
    })
}

impl Foreground {
    pub async fn end(mut self) {
        if let Some(proxy) = self.proxy.take() {
            end_foreground(&proxy).await;
        }
    }
}

impl Drop for Foreground {
    fn drop(&mut self) {
        if let Some(proxy) = self.proxy.take() {
            if let Ok(runtime) = tokio::runtime::Handle::try_current() {
                runtime.spawn(async move { end_foreground(&proxy).await });
            }
        }
    }
}

async fn end_foreground(proxy: &Proxy) {
    let answer =
        call_json::<Value>(proxy, "/worker/foreground/end", &json!({}), QUICK_TIMEOUT).await;
    if let Err(error) = answer {
        eprintln!("[server] couldn't tell the model worker a dictation ended: {error}");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_recognize_body_is_the_head_then_the_pcm() {
        let request = Recognize {
            rate: 16_000,
            ..Default::default()
        };
        let body = recognize_body(&request, &[1, -2]);
        let size = u32::from_le_bytes(body[..4].try_into().unwrap()) as usize;
        let head: Value = serde_json::from_slice(&body[4..4 + size]).unwrap();
        assert_eq!(head["rate"], 16_000);
        assert_eq!(head["alignment"], false);
        assert_eq!(&body[4 + size..], &[1, 0, 0xfe, 0xff]);
    }

    #[test]
    fn a_failure_reads_the_workers_detail() {
        let detail = br#"{"detail": "Download Qwen3 4B in Models to use Command Mode"}"#;
        assert_eq!(
            failure(StatusCode::UNPROCESSABLE_ENTITY, detail),
            "Download Qwen3 4B in Models to use Command Mode"
        );
        assert_eq!(
            failure(StatusCode::BAD_GATEWAY, b"down"),
            "502 Bad Gateway: down"
        );
    }
}
